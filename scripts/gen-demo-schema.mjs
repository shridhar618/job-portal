// Writes src/lib/demo-schema.ts: the SQL that creates every table in prisma/schema.prisma.
// Demo mode runs it in an in-memory Postgres (PGlite). Re-run after changing the schema:
//   npm run demo:schema
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execFileSync(
  "npx",
  ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/schema.prisma", "--script"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);
writeFileSync(
  "src/lib/demo-schema.ts",
  `// Generated by scripts/gen-demo-schema.mjs from prisma/schema.prisma. Do not edit by hand.\nexport const DEMO_SCHEMA_SQL = ${JSON.stringify(sql)};\n`,
);
console.log("Wrote src/lib/demo-schema.ts");
